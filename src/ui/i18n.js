let lang = 'en';

export function setLang(l) {
  lang = STR[l] ? l : 'en';
  document.documentElement.lang = lang;
}

export function getLang() {
  return lang;
}

// Italian first: quest and world texts are written in Italian; English is one setting away.
export function defaultLang() {
  return 'it';
}

export function t(key) {
  const v = STR[lang][key];
  return v === undefined ? STR.en[key] ?? key : v;
}
